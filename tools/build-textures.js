// Rebuilds js/textures.js from the two portrait images.
// Run after you change a photo:   node tools/build-textures.js
// (Needed because browsers block WebGL from reading local image files when
//  index.html is opened by double-clicking it. Base64 works everywhere.)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const toDataUri = (file) =>
  'data:image/png;base64,' + fs.readFileSync(path.join(root, file)).toString('base64');

const out =
  `// AUTO-GENERATED by tools/build-textures.js — do not edit by hand.\n` +
  `const BASE64_BW = "${toDataUri('assets/img/portrait-bw.png')}";\n` +
  `const BASE64_COLOR = "${toDataUri('assets/img/portrait-color.png')}";\n`;

fs.writeFileSync(path.join(root, 'js/textures.js'), out);
console.log('js/textures.js written (' + Math.round(out.length / 1024) + ' KB)');
